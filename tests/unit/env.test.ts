import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
const { loadEnvFile } = await import("../../server/env.ts");
const file = join(mkdtempSync(join(tmpdir(), "mirror-test-")), "test.env");
writeFileSync(file, "GROQ_API_KEY=gsk_brandnewkey1234\nVOICE_ECHO=0.3\nCANDY_RULE=Two treats each.   # comment\n");
process.env.GROQ_API_KEY = "gsk_oldsystemkey9999";
process.env.VOICE_ECHO = "0.3";
process.env.CANDY_RULE = "One treat.";
const notes = loadEnvFile(file);
let bad = 0;
const ok = (c: boolean, w: string) => { console.log(`${c ? "ok  " : "FAIL"} ${w}`); bad += c ? 0 : 1; };
ok(process.env.GROQ_API_KEY === "gsk_brandnewkey1234", ".env wins over a key set in the system");
ok(process.env.CANDY_RULE === "Two treats each.", ".env wins for other settings too (inline comment dropped)");
const key = notes.find((n) => n.startsWith("GROQ_API_KEY")) ?? "";
const candy = notes.find((n) => n.startsWith("CANDY_RULE")) ?? "";
ok(notes.length === 2 && key.includes("…9999") && key.includes("…1234") && !key.includes("oldsystemkey") && !key.includes("brandnewkey"), "the key clash is reported with only the last 4 characters");
ok(candy.includes("(One treat.)") && candy.includes("(Two treats each.)"), "a non-secret clash shows the values");
ok(!notes.some((n) => n.startsWith("VOICE_ECHO")), "the same value in both places is no clash");
ok(loadEnvFile("/nonexistent/.env").length === 0, "no .env file: nothing changes");
process.exit(bad ? 1 : 0);
